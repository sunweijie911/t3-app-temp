/**
 * 群聊正文里的 @机器人 前缀剥离。
 *
 * 三个平台推给我们的 `content` 都可能带着 "@机器人昵称 " 开头，但以前只有
 * 飞书（`@_user_N` 占位符）和钉钉做了处理，企微是原样透传的 —— 于是同一句
 * 「@小助手 记一笔 300」在企微上进 LLM 的是带 @ 的版本，也原样落进审计日志的
 * content 列。规则本身与平台无关，因此收在这里由三家共用。
 */

/**
 * 剥掉开头的一个 "@昵称"。
 *
 * 只剥一次、且只在群聊调用：
 * - 只剥一次 → "@机器人 @张三的进度" 会保留后面那个 @张三，它是业务内容
 * - 只在群聊 → 单聊平台不会加 @机器人，照剥会吃掉正文第一个 token
 *   （私聊「@张三 的项目进度」变成「的项目进度」）
 *
 * 匹配 "@昵称" 后跟空白（正常情况），或者整条消息就只有这个 @
 * （只 @ 了机器人什么都没写 —— 这时不能让 "@昵称" 残留成业务正文）。
 * 正文不以 @ 开头时原样返回，所以对「本来就不带前缀」的平台是无害的。
 */
export function stripLeadingMention(content: string): string {
  return content.replace(/^@\S+(?:\s+|$)/, '').trim();
}
